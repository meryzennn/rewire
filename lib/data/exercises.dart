/// Exercise definitions for Rewire bodyweight workouts (spec §4.1).
library;

class Exercise {
  const Exercise({
    required this.id,
    required this.name,
    required this.category,
    required this.defaultSets,
    required this.defaultReps,
    required this.isTimed,
    required this.unit,
    required this.difficulty,
    required this.description,
    required this.targetMuscles,
    required this.imageAssetPath,
    this.iconAssetPath,
    this.animationFrames = const [],
  });

  final String id;
  final String name;
  final String category; // 'Upper', 'Lower', 'Core', 'Cardio'
  final int defaultSets;
  final int defaultReps;
  final bool isTimed;
  final String unit; // 'Repetisi' or 'Detik'
  final String difficulty; // 'Beginner' or 'Intermediate'
  final String description;
  final String targetMuscles;
  final String imageAssetPath;
  final String? iconAssetPath;
  final List<String> animationFrames;
}

